"""Drafts in NOA's voice by borrowing her system prompt, without ever letting NOA act.

The ONLY NOA endpoint used is the read-only `POST /agents/{id}/prompt`, which returns
{"system_prompt": "..."} and runs no tools.

NOA's ENGINE_API_KEY is a single global key: the same Bearer token also authorizes
`POST /agents/{id}/chat` (a tool loop: send_whatsapp, issue_document, transfer_call,
webhooks, MCP) and `POST /calls` (real outbound phone calls). Read-only use is therefore
enforced here, in code, not by the key:

1. the agent id must match ^[a-z0-9][a-z0-9_-]{0,63}$ (no dots, slashes, encodings);
2. the base URL must be https (plain http only for localhost / 127.0.0.1 / ::1), with no
   credentials, query or fragment;
3. the exact request URL is computed once and an httpx request hook refuses anything that
   is not `POST` to exactly that scheme/host/port/path `.../agents/{id}/prompt`;
4. redirects are never followed and any 3xx counts as a failure.

RECOMMENDED: persona FILE mode (`persona_file` / BRIDGE_PERSONA_FILE). The persona is fetched
ONCE by the operator (`python -m bridge_service.admin export-persona --out <file>`, same
allowlist/redirect protections as below) and then read from that local UTF-8 file (max 20 KB,
re-read when its mtime/size changes). In file mode this engine never creates an HTTP client for
NOA, never sends a request to NOA and does not need the NOA key at all, so the key can be removed
from the bridge host's environment (security review H-1).

Any failure means "no persona": the draft is still produced, labelled `noa_persona:fallback`.
The draft itself is generated by the same tool-free Anthropic call as AnthropicEngine, with
the persona as tone/identity background inside <noa_persona>.
"""

from __future__ import annotations

import asyncio
import logging
import os
import re
import time
from collections.abc import Callable
from pathlib import Path
from urllib.parse import urlsplit

import httpx

from bridge_service.ai.anthropic_engine import AnthropicEngine
from bridge_service.ai.base import DraftInput, DraftOutput
from bridge_service.ai.safety import analyze_incoming

log = logging.getLogger(__name__)

PERSONA_TTL_SECONDS = 600.0
FAILURE_TTL_SECONDS = 60.0  # brief negative cache so a down NOA does not add 10s to every draft
PERSONA_TIMEOUT_SECONDS = 10.0
MAX_PERSONA_CHARS = 6000
MAX_PERSONA_FILE_BYTES = 20 * 1024
AGENT_ID_RE = re.compile(r"^[a-z0-9][a-z0-9_-]{0,63}$")
_LOCAL_HOSTS = frozenset({"localhost", "127.0.0.1", "::1"})
# Agent configs may carry unfilled template lines such as "[למלא: ...]"; /prompt does not
# check for them, so they are dropped before the persona is used.
_PLACEHOLDER = "[למלא"


class ForbiddenNoaEndpoint(RuntimeError):
    """Raised if anything other than POST to the read-only /prompt endpoint would be requested."""


class PersonaFetchError(RuntimeError):
    """The one /prompt request failed. The message is content-free (status / exception type only)."""


def validate_agent_id(agent_id: str) -> str:
    if not isinstance(agent_id, str) or not AGENT_ID_RE.fullmatch(agent_id):
        raise ValueError("invalid NOA agent id")
    return agent_id


def validate_base_url(base_url: str) -> str:
    parts = urlsplit(base_url)
    host = (parts.hostname or "").lower()
    if parts.scheme == "https":
        pass
    elif parts.scheme == "http" and host in _LOCAL_HOSTS:
        pass
    else:
        raise ValueError("NOA engine URL must be https (http only for localhost)")
    if not host or parts.username or parts.password or parts.query or parts.fragment:
        raise ValueError("invalid NOA engine URL")
    return base_url.rstrip("/")


def persona_url(base_url: str, agent_id: str) -> str:
    """The one URL this engine may call. Raises ValueError on bad input."""
    url = validate_base_url(base_url) + "/agents/" + validate_agent_id(agent_id) + "/prompt"
    assert_allowed("POST", url, url)
    return url


def _key(url: str) -> tuple[str, str, int | None, str]:
    p = urlsplit(url)
    port = p.port or (443 if p.scheme == "https" else 80)
    return (p.scheme, (p.hostname or "").lower(), port, p.path)


def assert_allowed(method: str, url: str, expected_url: str) -> None:
    """Explicit allowlist: exactly POST to exactly `expected_url` (a /agents/{id}/prompt URL)."""
    path = urlsplit(url).path
    if (
        method.upper() != "POST"
        or urlsplit(url).query
        or _key(url) != _key(expected_url)
        or not re.fullmatch(r"(?:/[^/]+)*/agents/[a-z0-9][a-z0-9_-]{0,63}/prompt", path)
        or "/chat" in path.lower()
        or "/calls" in path.lower()
    ):
        raise ForbiddenNoaEndpoint("only POST to the read-only NOA /prompt endpoint may be requested")


def clean_persona(prompt: str) -> str | None:
    """Drop unfilled placeholder lines, trim, cap. Returns None if nothing useful is left."""
    lines = [ln for ln in prompt.splitlines() if _PLACEHOLDER not in ln]
    cleaned = "\n".join(lines).strip()[:MAX_PERSONA_CHARS].strip()
    return cleaned or None


def make_guarded_client(expected_url: str | None, timeout: float) -> httpx.AsyncClient:
    """httpx client that never follows redirects and refuses every request except POST expected_url."""

    async def guard(request: httpx.Request) -> None:
        # Last check right before bytes leave the process.
        if expected_url is None:
            raise ForbiddenNoaEndpoint("NOA persona URL is not configured")
        assert_allowed(request.method, str(request.url), expected_url)

    return httpx.AsyncClient(
        timeout=timeout,
        follow_redirects=False,
        event_hooks={"request": [guard]},
    )


async def request_persona(client: httpx.AsyncClient, expected_url: str, api_key: str) -> str | None:
    """ONE POST to the read-only /prompt URL. Returns the cleaned persona (None if empty).

    Raises PersonaFetchError / ForbiddenNoaEndpoint on any failure; never follows a redirect.
    """
    assert_allowed("POST", expected_url, expected_url)
    try:
        resp = await client.post(
            expected_url,
            json={"variables": {}, "direction": "inbound"},
            headers={"Authorization": f"Bearer {api_key}"},
        )
    except ForbiddenNoaEndpoint:
        raise
    except Exception as exc:  # noqa: BLE001 - network errors, timeouts
        raise PersonaFetchError(f"request failed ({type(exc).__name__})") from None
    if resp.is_redirect or 300 <= resp.status_code < 400:
        raise PersonaFetchError(f"got a redirect (HTTP {resp.status_code}); not followed")
    if resp.status_code != 200:
        raise PersonaFetchError(f"HTTP {resp.status_code}")
    try:
        prompt = resp.json().get("system_prompt")
    except Exception:  # noqa: BLE001
        raise PersonaFetchError("response is not a JSON object") from None
    if not isinstance(prompt, str):
        raise PersonaFetchError("response has no system_prompt")
    return clean_persona(prompt)


class PersonaFile:
    """Reads the persona from a local file; re-reads only when (mtime_ns, size) changes.

    No network. Any problem (missing, > 20 KB, not UTF-8, empty) means "no persona".
    """

    def __init__(self, path: str | os.PathLike[str], max_bytes: int = MAX_PERSONA_FILE_BYTES) -> None:
        self.path = Path(path)
        self.max_bytes = max_bytes
        self._sig: tuple[int, int] | None = None
        self._persona: str | None = None

    def get(self) -> str | None:
        try:
            st = os.stat(self.path)
        except OSError as exc:
            if self._sig != (-1, -1):
                log.warning("persona file unavailable (%s); drafting without persona", type(exc).__name__)
            self._sig, self._persona = (-1, -1), None
            return None
        sig = (st.st_mtime_ns, st.st_size)
        if sig == self._sig:
            return self._persona
        self._sig = sig
        self._persona = self._read(st.st_size)
        return self._persona

    def _read(self, size: int) -> str | None:
        if size > self.max_bytes:
            log.warning("persona file is larger than %d bytes; ignored", self.max_bytes)
            return None
        try:
            with open(self.path, "rb") as fh:
                raw = fh.read(self.max_bytes + 1)
        except OSError as exc:
            log.warning("persona file unreadable (%s)", type(exc).__name__)
            return None
        if len(raw) > self.max_bytes:
            log.warning("persona file is larger than %d bytes; ignored", self.max_bytes)
            return None
        try:
            text = raw.decode("utf-8-sig")
        except UnicodeDecodeError:
            log.warning("persona file is not valid UTF-8; ignored")
            return None
        persona = clean_persona(text)
        if persona is None:
            log.warning("persona file is empty after removing placeholder lines")
        return persona


class NoaPersonaEngine:
    name = "noa_persona"

    def __init__(
        self,
        noa_engine_url: str | None,
        noa_engine_api_key: str | None,
        noa_agent_id: str | None,
        generator: AnthropicEngine,
        *,
        persona_timeout: float = PERSONA_TIMEOUT_SECONDS,
        cache_ttl: float = PERSONA_TTL_SECONDS,
        failure_ttl: float = FAILURE_TTL_SECONDS,
        clock: Callable[[], float] = time.monotonic,
        persona_file: str | os.PathLike[str] | None = None,
    ) -> None:
        self._generator = generator
        self._file: PersonaFile | None = None
        if persona_file is not None and str(persona_file).strip():
            # File mode: the NOA URL/key are ignored entirely — no client, no expected URL, no key.
            self._file = PersonaFile(str(persona_file).strip())
            noa_engine_url = noa_engine_api_key = None
        self._base = (noa_engine_url or "").strip()
        self._key = noa_engine_api_key or ""
        self._agent_id = (noa_agent_id or "").strip()
        self._timeout = persona_timeout
        self._ttl = cache_ttl
        self._failure_ttl = failure_ttl
        self._clock = clock
        # Keyed by agent id only: the persona is the owner's agent config, not conversation data.
        self._cache: dict[str, tuple[str | None, float]] = {}
        self._lock = asyncio.Lock()
        self._http: httpx.AsyncClient | None = None
        self._expected_url: str | None = None
        try:
            if self._base and self._agent_id:
                self._expected_url = persona_url(self._base, self._agent_id)
        except ValueError as exc:
            log.warning("NOA persona disabled: %s", exc)

    @property
    def file_mode(self) -> bool:
        return self._file is not None

    def _client(self) -> httpx.AsyncClient:
        if self._file is not None:  # defence in depth: file mode never talks to NOA
            raise ForbiddenNoaEndpoint("persona file mode makes no NOA requests")
        if self._http is None:
            self._http = make_guarded_client(self._expected_url, self._timeout)
        return self._http

    async def _fetch(self) -> str | None:
        if self._file is not None:
            return None
        if not (self._expected_url and self._key):
            log.info("NOA persona not configured or invalid; drafting without persona")
            return None
        try:
            return await request_persona(self._client(), self._expected_url, self._key)
        except ForbiddenNoaEndpoint:
            log.error("blocked a NOA request outside the /prompt allowlist")
            return None
        except PersonaFetchError as exc:
            log.warning("NOA persona fetch failed: %s", exc)
            return None
        except Exception as exc:  # noqa: BLE001 - any failure means "no persona"
            log.warning("NOA persona fetch failed: %s", type(exc).__name__)
            return None

    async def get_persona(self) -> str | None:
        if self._file is not None:
            return self._file.get()
        key = self._agent_id
        hit = self._cache.get(key)
        if hit and hit[1] > self._clock():
            return hit[0]
        async with self._lock:
            hit = self._cache.get(key)
            if hit and hit[1] > self._clock():
                return hit[0]
            persona = await self._fetch()
            ttl = self._ttl if persona is not None else self._failure_ttl
            self._cache[key] = (persona, self._clock() + ttl)
            return persona

    async def draft(self, data: DraftInput) -> DraftOutput:
        report = analyze_incoming(data.messages, sender_display_name=data.sender_display_name)
        persona = await self.get_persona()
        text = await self._generator.generate(data, report, persona=persona)
        label = self.name if persona is not None else f"{self.name}:fallback"
        return DraftOutput(draft_text=text, safety=report, engine=label)

    async def aclose(self) -> None:
        if self._http is not None:
            await self._http.aclose()
            self._http = None
        await self._generator.aclose()


