"""Drafts in NOA's voice by borrowing her system prompt, without ever letting NOA act.

The ONLY NOA endpoint used is the read-only `POST /agents/{id}/prompt`, which returns
{"system_prompt": "..."} and runs no tools. `POST /agents/{id}/chat` runs real tools
(send_whatsapp, issue_document, transfer_call, webhooks, MCP) and is never called: the
URL is built from a fixed template, the agent id is validated and percent-encoded, every
URL is checked before sending, and redirects are not followed.

The draft itself is generated by the same tool-free Anthropic call as AnthropicEngine,
with the persona as background inside <noa_persona>.
"""

from __future__ import annotations

import asyncio
import logging
import re
import time
from collections.abc import Callable
from urllib.parse import quote, urlsplit

import httpx

from bridge_service.ai.anthropic_engine import AnthropicEngine
from bridge_service.ai.base import DraftInput, DraftOutput
from bridge_service.ai.safety import analyze_incoming

log = logging.getLogger(__name__)

PERSONA_TTL_SECONDS = 600.0
FAILURE_TTL_SECONDS = 60.0  # brief negative cache so a down NOA does not add 10s to every draft
PERSONA_TIMEOUT_SECONDS = 10.0
MAX_PERSONA_CHARS = 6000
_AGENT_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_\-.]{0,127}$")


class ForbiddenNoaEndpoint(RuntimeError):
    """Raised if anything other than the read-only /prompt endpoint would be requested."""


def persona_url(base_url: str, agent_id: str) -> str:
    """Build and validate the /prompt URL. Raises ForbiddenNoaEndpoint / ValueError."""
    if not _AGENT_ID.match(agent_id) or ".." in agent_id:
        raise ValueError("invalid NOA agent id")
    parts = urlsplit(base_url)
    if parts.scheme not in ("http", "https") or not parts.netloc or parts.query or parts.fragment:
        raise ValueError("invalid NOA engine URL")
    url = base_url.rstrip("/") + "/agents/" + quote(agent_id, safe="") + "/prompt"
    assert_allowed(url)
    return url


def assert_allowed(url: str) -> None:
    path = urlsplit(url).path
    if "/chat" in path.lower() or not path.endswith("/prompt") or "/agents/" not in path:
        raise ForbiddenNoaEndpoint("only the read-only NOA /prompt endpoint may be called")


class NoaPersonaEngine:
    name = "noa_persona"

    def __init__(
        self,
        noa_engine_url: str | None,
        noa_engine_api_key: str | None,
        noa_agent_id: str | None,
        generator: AnthropicEngine,
        *,
        persona_timeout: float = PERSONA_TIMEOUT_SECONDS,
        cache_ttl: float = PERSONA_TTL_SECONDS,
        failure_ttl: float = FAILURE_TTL_SECONDS,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self._url = (noa_engine_url or "").strip()
        self._key = noa_engine_api_key or ""
        self._agent_id = (noa_agent_id or "").strip()
        self._generator = generator
        self._timeout = persona_timeout
        self._ttl = cache_ttl
        self._failure_ttl = failure_ttl
        self._clock = clock
        # Keyed by agent id only: the persona is the owner's agent config, not conversation data.
        self._cache: dict[str, tuple[str | None, float]] = {}
        self._lock = asyncio.Lock()
        self._http: httpx.AsyncClient | None = None

    def _client(self) -> httpx.AsyncClient:
        if self._http is None:
            self._http = httpx.AsyncClient(
                timeout=self._timeout,
                follow_redirects=False,
                event_hooks={"request": [self._guard_request]},
            )
        return self._http

    @staticmethod
    async def _guard_request(request: httpx.Request) -> None:
        assert_allowed(str(request.url))

    async def _fetch(self) -> str | None:
        if not (self._url and self._key and self._agent_id):
            log.info("NOA persona not configured; drafting without persona")
            return None
        try:
            url = persona_url(self._url, self._agent_id)
            resp = await self._client().post(
                url,
                json={"variables": {}, "direction": "inbound"},
                headers={"Authorization": f"Bearer {self._key}"},
            )
            if resp.status_code != 200:
                log.warning("NOA persona fetch failed: HTTP %s", resp.status_code)
                return None
            prompt = resp.json().get("system_prompt")
            if not isinstance(prompt, str) or not prompt.strip():
                log.warning("NOA persona fetch returned no system_prompt")
                return None
            return prompt.strip()[:MAX_PERSONA_CHARS]
        except ForbiddenNoaEndpoint:
            raise
        except Exception as exc:  # noqa: BLE001 - any failure means "no persona"
            log.warning("NOA persona fetch failed: %s", type(exc).__name__)
            return None

    async def get_persona(self) -> str | None:
        key = self._agent_id
        now = self._clock()
        hit = self._cache.get(key)
        if hit and hit[1] > now:
            return hit[0]
        async with self._lock:
            now = self._clock()
            hit = self._cache.get(key)
            if hit and hit[1] > now:
                return hit[0]
            persona = await self._fetch()
            ttl = self._ttl if persona is not None else self._failure_ttl
            self._cache[key] = (persona, self._clock() + ttl)
            return persona

    async def draft(self, data: DraftInput) -> DraftOutput:
        report = analyze_incoming(data.messages)
        persona = await self.get_persona()
        text = await self._generator.generate(data, report, persona=persona)
        label = self.name if persona is not None else f"{self.name}:fallback"
        return DraftOutput(draft_text=text, safety=report, engine=label)

    async def aclose(self) -> None:
        if self._http is not None:
            await self._http.aclose()
            self._http = None
        await self._generator.aclose()


__all__ = ["NoaPersonaEngine", "ForbiddenNoaEndpoint", "persona_url", "assert_allowed"]
