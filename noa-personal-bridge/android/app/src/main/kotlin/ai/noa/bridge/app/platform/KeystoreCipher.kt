package ai.noa.bridge.app.platform

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import java.security.GeneralSecurityException
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Small string cipher abstraction so storage can be tested without AndroidKeyStore (absent on Robolectric). */
interface SecretCipher {
    fun encrypt(plaintext: String): String

    /**
     * Returns null when the value cannot be decrypted (key deleted or invalidated, data corrupted,
     * tampered, keystore error). Implementations should not throw; [SecureStore] also guards it.
     */
    fun decrypt(encoded: String): String?

    /** Permanently deletes the key; everything encrypted with it becomes unreadable. */
    fun destroyKey()
}

/**
 * AES-256-GCM with a non-exportable key in AndroidKeyStore (TEE-backed on the S25 Ultra).
 * Output: base64(NO_WRAP) of `iv(12 bytes) || ciphertext+tag(128-bit)`; a fresh random IV is
 * generated by the keystore for every encryption.
 *
 * Choices (documented for the security review):
 * - No user-authentication binding and no `setUnlockedDeviceRequired`: the device token must be
 *   readable while the phone is locked, because drafts are requested in the background when a
 *   notification arrives. Sending still requires an unlocked device (checked in the controller).
 * - Not StrongBox: StrongBox AES is slow and may throw StrongBoxUnavailableException; TEE is the
 *   standard for app secrets.
 */
class KeystoreCipher(private val alias: String = DEFAULT_ALIAS) : SecretCipher {

    @Synchronized
    private fun key(): SecretKey {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        (keyStore.getKey(alias, null) as? SecretKey)?.let { return it }
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(alias, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .setRandomizedEncryptionRequired(true)
                .build(),
        )
        return generator.generateKey()
    }

    /** May throw GeneralSecurityException / ProviderException; [SecureStore] catches and stores nothing. */
    override fun encrypt(plaintext: String): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key())
        val iv = cipher.iv
        check(iv.size == IV_BYTES) { "unexpected iv size" }
        val ciphertext = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))
        return Base64.encodeToString(iv + ciphertext, Base64.NO_WRAP)
    }

    override fun decrypt(encoded: String): String? = try {
        val bytes = Base64.decode(encoded, Base64.NO_WRAP)
        if (bytes.size <= IV_BYTES) {
            null
        } else {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(TAG_BITS, bytes, 0, IV_BYTES))
            String(cipher.doFinal(bytes, IV_BYTES, bytes.size - IV_BYTES), Charsets.UTF_8)
        }
    } catch (e: GeneralSecurityException) {
        // Includes KeyStoreException, AEADBadTagException, UnrecoverableKeyException.
        SafeLog.e(SafeLog.Event.SECURE_STORE_DECRYPT_FAILED, e)
        null
    } catch (e: java.io.IOException) {
        // KeyStore.load() failure.
        SafeLog.e(SafeLog.Event.SECURE_STORE_DECRYPT_FAILED, e)
        null
    } catch (e: RuntimeException) {
        // ProviderException (keystore daemon errors, invalidated key), IllegalStateException,
        // IllegalArgumentException (bad base64), ClassCastException: the value counts as absent.
        SafeLog.e(SafeLog.Event.SECURE_STORE_DECRYPT_FAILED, e)
        null
    }

    @Synchronized
    override fun destroyKey() {
        try {
            KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }.deleteEntry(alias)
        } catch (e: GeneralSecurityException) {
            SafeLog.e(SafeLog.Event.SECURE_STORE_DECRYPT_FAILED, e)
        } catch (e: java.io.IOException) {
            SafeLog.e(SafeLog.Event.SECURE_STORE_DECRYPT_FAILED, e)
        }
    }

    companion object {
        const val DEFAULT_ALIAS = "noa_bridge_master"
        private const val ANDROID_KEYSTORE = "AndroidKeyStore"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val IV_BYTES = 12
        private const val TAG_BITS = 128
    }
}
