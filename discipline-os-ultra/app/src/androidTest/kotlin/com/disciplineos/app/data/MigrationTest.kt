package com.disciplineos.app.data

import androidx.room.Room
import androidx.room.testing.MigrationTestHelper
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.disciplineos.app.data.local.DisciplineDatabase
import com.disciplineos.app.data.local.Migrations
import kotlinx.coroutines.test.runTest
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import java.time.LocalDate

/**
 * Requires app/schemas/.../1.json and 2.json packaged as androidTest assets (the Room Gradle plugin does this).
 * 1.json is hand-maintained history; 2.json is regenerated by Room on build (see docs/DATABASE.md).
 */
@RunWith(AndroidJUnit4::class)
class MigrationTest {

    private val dbName = "migration-test.db"

    @get:Rule
    val helper = MigrationTestHelper(
        InstrumentationRegistry.getInstrumentation(),
        DisciplineDatabase::class.java,
    )

    private val day = LocalDate.of(2026, 11, 4).toEpochDay()

    private fun seedV1() {
        helper.createDatabase(dbName, 1).apply {
            execSQL(
                "INSERT INTO tasks (id, title, notes, kind, priority, categoryId, startDate, dueTime, endDate, zoneId, " +
                    "recurrence, reminderOffsets, estimatedMinutes, verification, archived, createdAt, updatedAt) " +
                    "VALUES (1, 'Read', '', 'MANDATORY', 'HIGH', NULL, $day, 64800, NULL, 'Asia/Jerusalem', '', '10', NULL, 'NONE', 0, 1000, 1000)",
            )
            execSQL("INSERT INTO task_occurrences (id, taskId, localDate, dueAt, status, completedAt, snoozedUntil) VALUES (10, 1, $day, 5000, 'PENDING', NULL, 9000)")
            execSQL("INSERT INTO task_occurrences (id, taskId, localDate, dueAt, status, completedAt, snoozedUntil) VALUES (11, 1, ${day + 1}, NULL, 'COMPLETED', 7000, NULL)")
            // Occurrence 10 was snoozed twice before v2 existed.
            execSQL("INSERT INTO task_history (id, taskId, occurrenceId, type, at, detail) VALUES (1, 1, 10, 'SNOOZED', 100, '')")
            execSQL("INSERT INTO task_history (id, taskId, occurrenceId, type, at, detail) VALUES (2, 1, 10, 'SNOOZED', 200, '')")
            execSQL("INSERT INTO task_history (id, taskId, occurrenceId, type, at, detail) VALUES (3, 1, 11, 'COMPLETED', 300, '')")
            execSQL("INSERT INTO xp_events (id, at, amount, source, dedupeKey) VALUES (1, 7000, 20, 'TASK_COMPLETED', 'occ:11')")
            close()
        }
    }

    @Test
    fun migrate1To2_preservesData_andSetsDefaults() {
        seedV1()
        // Validates the migrated schema against 2.json (columns, defaults, indices, foreign keys).
        val db = helper.runMigrationsAndValidate(dbName, 2, true, Migrations.MIGRATION_1_2)

        db.query("SELECT id, status, dueAt, snoozedUntil, snoozeCount, verificationNote FROM task_occurrences ORDER BY id").use { c ->
            assertEquals(2, c.count)
            c.moveToFirst()
            assertEquals(10L, c.getLong(0))
            assertEquals("PENDING", c.getString(1))
            assertEquals(5000L, c.getLong(2))
            assertEquals(9000L, c.getLong(3))
            assertEquals(2, c.getInt(4)) // back-filled from history
            assertEquals(true, c.isNull(5))
            c.moveToNext()
            assertEquals(11L, c.getLong(0))
            assertEquals("COMPLETED", c.getString(1))
            assertEquals(0, c.getInt(4)) // default
            assertEquals(true, c.isNull(5))
        }
        db.query("SELECT COUNT(*) FROM xp_events").use { c -> c.moveToFirst(); assertEquals(1, c.getInt(0)) }
        db.query("SELECT COUNT(*) FROM task_history").use { c -> c.moveToFirst(); assertEquals(3, c.getInt(0)) }

        // New rows get the DEFAULT 0 without naming the column.
        db.execSQL("INSERT INTO task_occurrences (taskId, localDate, dueAt, status, completedAt, snoozedUntil) VALUES (1, ${day + 2}, NULL, 'PENDING', NULL, NULL)")
        db.query("SELECT snoozeCount FROM task_occurrences WHERE localDate = ${day + 2}").use { c -> c.moveToFirst(); assertEquals(0, c.getInt(0)) }
    }

    /**
     * Opens the migrated file with the real, compiled Room database. Room validates the schema against the
     * generated entity code here, so this catches any drift between 1.json + MIGRATION_1_2 and the entities.
     */
    @Test
    fun migratedDatabase_opensWithRoom_andDaosWork() = runTest {
        seedV1()
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val room = Room.databaseBuilder(context, DisciplineDatabase::class.java, dbName)
            .addMigrations(*Migrations.ALL)
            .build()
        helper.closeWhenFinished(room)
        val occ = room.taskDao().getOccurrence(10)!!
        assertEquals(2, occ.snoozeCount)
        assertNull(occ.verificationNote)
        assertEquals(1, room.taskDao().getAllActiveTasks().size)
    }
}
