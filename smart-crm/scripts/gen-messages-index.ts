/**
 * Writes src/i18n/messages.generated.ts, which statically imports every
 * messages/<locale>/<namespace>.json file. Each module owns its own namespace
 * file, so parallel work never edits a shared catalog.  Run: npm run i18n:index
 */
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const locales = ["he", "en"];
const namespaces = readdirSync(path.join(root, "messages", "he"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))
  .sort();

const ident = (loc: string, ns: string) => `${loc}_${ns.replace(/[^a-zA-Z0-9]/g, "_")}`;
const lines = ["// AUTO-GENERATED by scripts/gen-messages-index.ts — do not edit.", ""];
for (const loc of locales) for (const ns of namespaces) lines.push(`import ${ident(loc, ns)} from "../../messages/${loc}/${ns}.json";`);
lines.push("");
for (const loc of locales) {
  lines.push(`export const ${loc} = {`);
  for (const ns of namespaces) lines.push(`  ${JSON.stringify(ns)}: ${ident(loc, ns)},`);
  lines.push("};");
}
lines.push("", "export const messagesByLocale = { he, en };", "");
writeFileSync(path.join(root, "src", "i18n", "messages.generated.ts"), lines.join("\n"));
console.log(`messages index: ${namespaces.length} namespaces`);
