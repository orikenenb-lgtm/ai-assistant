/**
 * Bundles every migration into one SQL file for the Supabase SQL Editor:
 *
 *   npm run db:bundle   →  supabase/deploy/all-migrations.sql
 *
 * The bundle runs in a single transaction (all or nothing) and records each
 * version in supabase_migrations.schema_migrations, exactly like
 * `npm run db:migrate`, so later migrations can be applied with either tool.
 * Meant for a fresh project; on a database that already has some migrations,
 * use `npm run db:migrate` instead.
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const MIGRATIONS_DIR = path.join(ROOT, "supabase", "migrations");
const OUT = path.join(ROOT, "supabase", "deploy", "all-migrations.sql");
const TAG = "$smartcrm_migration$";

const files = (await readdir(MIGRATIONS_DIR)).filter((f) => f.endsWith(".sql")).sort();
const parts: string[] = [
  "-- SMART CRM AI — all migrations in one transaction (generated by `npm run db:bundle`; do not edit).",
  "-- Paste into Supabase → SQL Editor on a NEW project and run once.",
  "begin;",
  "create schema if not exists supabase_migrations;",
  "create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);",
  "do $guard$ begin",
  "  if exists (select 1 from supabase_migrations.schema_migrations where version like '2026%') then",
  "    raise exception 'SMART CRM migrations were already applied here: use npm run db:migrate for new ones';",
  "  end if;",
  "end $guard$;",
];
for (const file of files) {
  const m = /^(\d{14})_(.+)\.sql$/.exec(file);
  if (!m) throw new Error(`Invalid migration file name: ${file}`);
  const body = await readFile(path.join(MIGRATIONS_DIR, file), "utf8");
  if (body.includes(TAG)) throw new Error(`${file} contains the reserved quote tag ${TAG}`);
  parts.push(
    `\n-- ===== ${file} =====\n`,
    body.trimEnd(),
    `\ninsert into supabase_migrations.schema_migrations (version, name, statements) values ('${m[1]}', '${m[2]}', array[${TAG}${body}${TAG}]);`,
  );
}
parts.push("\ncommit;\n");
await mkdir(path.dirname(OUT), { recursive: true });
await writeFile(OUT, parts.join("\n"));
console.log(`bundled ${files.length} migrations → ${path.relative(ROOT, OUT)}`);
